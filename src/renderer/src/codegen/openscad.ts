const HEADER = [
  '// Generated by 3dev-editor. Requires BOSL2 (https://github.com/BelfrySCAD/BOSL2).',
  'include <BOSL2/std.scad>'
]

export interface ScadSourceFile {
  path: string
  source: string
}

export function generateOpenscad(
  document: ProjectDocument,
  fileName = document.activeFile
): string {
  const uses = componentNamesIn(document.files[fileName]?.nodes ?? {}).map(
    (name) => `use <${scadRelativePath(fileName, name)}>`
  )
  const lines = [...HEADER]
  if (uses.length > 0) lines.push(...uses)
  lines.push('', `$fn = ${formatNumber(document.fn)};`, '')
  const body = getRoots(document, fileName)
    .filter((node) => node.visible)
    .map((node) => emitFeature(document, node, fileName))
    .filter((part) => part.length > 0)
  const content = body.length > 0 ? body.join('\n') : '// Empty model'
  if (fileName === MAIN_FILE) {
    lines.push(content, '')
    return lines.join('\n')
  }
  lines.push(`module ${fileName}() {`, indent(content, 4), '}', '', `${fileName}();`, '')
  return lines.join('\n')
}

export function generateProjectSources(document: ProjectDocument): ScadSourceFile[] {
  return orderedFileNames(document).map((fileName) => ({
    path: projectEntryPath(fileName),
    source: generateOpenscad(document, fileName)
  }))
}

export function activeEntryPath(document: ProjectDocument): string {
  return projectEntryPath(document.activeFile)
}

export function formatNumber(value: number): string {
  if (!Number.isFinite(value)) return '0'
  const rounded = Math.round(value * 1000) / 1000
  return String(Object.is(rounded, -0) ? 0 : rounded)
}

function emitFeature(document: ProjectDocument, node: FeatureNode, fileName: string): string {
  if (!node.visible) return ''
  const shape = emitShape(document, node, fileName)
  if (!shape) return ''
  const scaled = emitScale(shape, isComponentNode(node) ? node.scale : null)
  const rotated = emitRotate(scaled, node.transform.rotation)
  const translated = emitTranslate(rotated, node.transform.position)
  return emitColor(translated, node.appearance, isGroupNode(node))
}

function emitShape(document: ProjectDocument, node: FeatureNode, fileName: string): string {
  if (isGroupNode(node) && !isGroupEnabled(node)) return emitInactiveGroup(document, node, fileName)
  if (isCuboidNode(node)) return `${emitCuboid(node)};`
  if (isCylinderNode(node)) return `${emitCylinder(node)};`
  if (isSphereNode(node)) return `${emitSphere(node)};`
  if (isComponentNode(node)) return `${node.componentName}();`
  if (isProfileNode(node)) return emitExtruded(node, fileName)
  if (isBooleanNode(node)) return emitBoolean(document, node, fileName)
  if (isOffsetNode(node) || isHull2dNode(node) || isProjectionNode(node)) {
    return emitExtrudedFlat(document, node, fileName)
  }
  if (isRevolveNode(node)) return emitRevolve(document, node, fileName)
  if (isHullNode(node)) return emitGroupCall(document, node, fileName, 'hull()')
  if (isMirrorNode(node)) return emitMirror(document, node, fileName)
  if (isResizeNode(node)) return emitResize(document, node, fileName)
  if (isMinkowskiNode(node)) return emitGroupCall(document, node, fileName, 'minkowski()')
  return ''
}

function emitFlatFeature(document: ProjectDocument, node: FeatureNode, fileName: string): string {
  if (!node.visible || !hasFlatForm(node)) return ''
  const shape = emitFlatShape(document, node, fileName)
  if (!shape) return ''
  const rotated = emitRotate(shape, node.transform.rotation)
  const translated = emitTranslate(rotated, node.transform.position)
  return emitColor(translated, node.appearance, isGroupNode(node))
}

function emitInactiveGroup(document: ProjectDocument, node: FeatureNode, fileName: string): string {
  if (!isGroupNode(node)) return ''
  const nodes = document.files[fileName]?.nodes ?? {}
  const parts = node.childIds
    .map((id) => nodes[id])
    .filter((child): child is FeatureNode => child !== undefined && child.visible)
    .map((child) => emitFeature(document, child, fileName))
    .filter((part) => part.length > 0)
  if (parts.length === 0) return ''
  if (parts.length === 1) return parts[0]
  return `union() {\n${indent(parts.join('\n'), 4)}\n}`
}

function emitFlatShape(document: ProjectDocument, node: FeatureNode, fileName: string): string {
  if (isGroupNode(node) && !isGroupEnabled(node)) return emitInactiveFlat(document, node, fileName)
  if (isProfileNode(node)) return emitProfile2d(node, fileName)
  if (isOffsetNode(node)) return emitOffset(document, node, fileName)
  if (isHull2dNode(node)) return emitHull2d(document, node, fileName)
  if (isProjectionNode(node)) return emitProjection(document, node, fileName)
  return ''
}

function emitInactiveFlat(document: ProjectDocument, node: FeatureNode, fileName: string): string {
  if (!isGroupNode(node)) return ''
  const nodes = document.files[fileName]?.nodes ?? {}
  const parts = node.childIds
    .map((id) => nodes[id])
    .filter(
      (child): child is FeatureNode => child !== undefined && child.visible && hasFlatForm(child)
    )
    .map((child) => emitFlatFeature(document, child, fileName))
    .filter((part) => part.length > 0)
  if (parts.length === 0) return ''
  if (parts.length === 1) return parts[0]
  return `union() {\n${indent(parts.join('\n'), 4)}\n}`
}

function emitExtrudedFlat(
  document: ProjectDocument,
  node: OffsetNode | Hull2dNode | ProjectionNode,
  fileName: string
): string {
  const profile = emitFlatShape(document, node, fileName)
  if (!profile) return ''
  return `linear_extrude(${emitExtrusion(node.extrusion)}) {\n${indent(profile, 4)}\n}`
}

export function emitProfile2d(node: ProfileNode, fileName = MAIN_FILE): string {
  if (isRectNode(node)) return `${emitRect(node)};`
  if (isCircleNode(node)) return `${emitCircle(node)};`
  if (isEllipseNode(node)) return `${emitEllipse(node)};`
  if (isNgonNode(node)) return `${emitNgon(node)};`
  if (isStarNode(node)) return `${emitStar(node)};`
  if (isTextNode(node)) return `${emitText(node)};`
  if (isSvgNode(node)) return emitSvg(node, fileName)
  return ''
}

function emitExtruded(node: ProfileNode, fileName: string): string {
  const profile = emitProfile2d(node, fileName)
  if (!profile) return ''
  return `linear_extrude(${emitExtrusion(node.extrusion)}) {\n${indent(profile, 4)}\n}`
}

function emitExtrusion(extrusion: Extrusion): string {
  return [
    `height=${formatNumber(extrusion.height)}`,
    'center=true',
    `twist=${formatNumber(extrusion.twist)}`,
    `scale=${formatNumber(extrusion.scale)}`
  ].join(', ')
}

function emitRect(node: RectNode): string {
  const args = [`size=${emitVec2(node.size)}`]
  if (node.rounding > 0) args.push(`rounding=${formatNumber(node.rounding)}`)
  else if (node.chamfer > 0) args.push(`chamfer=${formatNumber(node.chamfer)}`)
  args.push('anchor=CENTER')
  return `rect(${args.join(', ')})`
}

function emitCircle(node: CircleNode): string {
  return `circle(d=${formatNumber(node.diameter)}, anchor=CENTER)`
}

function emitEllipse(node: EllipseNode): string {
  return `ellipse(d=${emitVec2(node.diameter)}, anchor=CENTER)`
}

function emitNgon(node: NgonNode): string {
  const args = [`n=${Math.round(node.sides)}`, `d=${formatNumber(node.diameter)}`]
  if (node.rounding > 0) args.push(`rounding=${formatNumber(node.rounding)}`)
  args.push('anchor=CENTER')
  return `regular_ngon(${args.join(', ')})`
}

function emitStar(node: StarNode): string {
  return `star(n=${Math.round(node.points)}, d=${formatNumber(node.diameter)}, id=${formatNumber(node.innerDiameter)}, anchor=CENTER)`
}

function emitText(node: TextNode): string {
  return [
    `text(text=${emitString(node.text)}`,
    `size=${formatNumber(node.size)}`,
    `font=${emitString(node.font)}`,
    `halign=${emitString(node.halign)}`,
    `valign=${emitString(node.valign)}`,
    'anchor=CENTER)'
  ].join(', ')
}

function emitSvg(node: SvgNode, fileName: string): string {
  const file = `${assetRelativePrefix(fileName)}${node.assetId}.svg`
  let body = `import(${emitString(file)});`
  const correction = svgImportCorrection(node.viewMin, node.mmPerUnit)
  if (!isNearlyZero(correction)) {
    body = `translate(${emitVec({ x: correction.x, y: correction.y, z: 0 })})\n${indent(body, 4)}`
  }
  if (Math.abs(node.importScale - 1) > 0.0005) {
    body = `scale(${emitVec({ x: node.importScale, y: node.importScale, z: 1 })})\n${indent(body, 4)}`
  }
  return `translate(${emitVec({ x: node.center.x, y: node.center.y, z: 0 })})\n${indent(body, 4)}`
}

function isNearlyZero(value: Vec2): boolean {
  return Math.abs(value.x) < 0.0005 && Math.abs(value.y) < 0.0005
}

function emitCuboid(node: CuboidNode): string {
  const args = [emitVec(node.size)]
  if (node.rounding > 0) args.push(`rounding=${formatNumber(node.rounding)}`)
  else if (node.chamfer > 0) args.push(`chamfer=${formatNumber(node.chamfer)}`)
  args.push('anchor=CENTER')
  return `cuboid(${args.join(', ')})`
}

function emitCylinder(node: CylinderNode): string {
  return `cyl(h=${formatNumber(node.height)}, d=${formatNumber(node.diameter)}, anchor=CENTER)`
}

function emitSphere(node: SphereNode): string {
  return `spheroid(d=${formatNumber(node.diameter)}, anchor=CENTER)`
}

function emitOffset(document: ProjectDocument, node: OffsetNode, fileName: string): string {
  const children = emitFlatChildren(document, node, fileName)
  if (!children) return ''
  return `${emitOffsetCall(node)} {\n${indent(children, 4)}\n}`
}

function emitOffsetCall(node: OffsetNode): string {
  if (node.mode === 'radius') return `offset(r=${formatNumber(node.distance)})`
  if (node.chamfer) return `offset(delta=${formatNumber(node.distance)}, chamfer=true)`
  return `offset(delta=${formatNumber(node.distance)})`
}

function emitHull2d(document: ProjectDocument, node: Hull2dNode, fileName: string): string {
  const children = emitFlatChildren(document, node, fileName)
  if (!children) return ''
  return `hull() {\n${indent(children, 4)}\n}`
}

function emitProjection(document: ProjectDocument, node: ProjectionNode, fileName: string): string {
  const children = emitSolidChildren(document, node, fileName)
  if (!children) return ''
  return `projection(cut=${node.cut ? 'true' : 'false'}) {\n${indent(children, 4)}\n}`
}

function emitRevolve(document: ProjectDocument, node: RevolveNode, fileName: string): string {
  const children = emitFlatChildren(document, node, fileName)
  if (!children) return ''
  const args = [`angle=${formatNumber(node.angle)}`]
  if (node.start !== 0) args.push(`start=${formatNumber(node.start)}`)
  return `rotate_extrude(${args.join(', ')}) {\n${indent(children, 4)}\n}`
}

function emitMirror(document: ProjectDocument, node: MirrorNode, fileName: string): string {
  const children = emitSolidChildren(document, node, fileName)
  if (!children) return ''
  const normal =
    node.axis === 'x'
      ? { x: 1, y: 0, z: 0 }
      : node.axis === 'y'
        ? { x: 0, y: 1, z: 0 }
        : { x: 0, y: 0, z: 1 }
  return `mirror(${emitVec(normal)}) {\n${indent(children, 4)}\n}`
}

function emitResize(document: ProjectDocument, node: ResizeNode, fileName: string): string {
  const children = emitSolidChildren(document, node, fileName)
  if (!children) return ''
  return `resize(${emitVec(node.size)}, auto=${node.auto ? 'true' : 'false'}) {\n${indent(children, 4)}\n}`
}

function emitGroupCall(
  document: ProjectDocument,
  node: HullNode | MinkowskiNode,
  fileName: string,
  call: string
): string {
  const children = emitSolidChildren(document, node, fileName)
  if (!children) return ''
  return `${call} {\n${indent(children, 4)}\n}`
}

function emitFlatChildren(document: ProjectDocument, node: FeatureNode, fileName: string): string {
  return emitListedChildren(document, node, fileName, (child) =>
    emitFlatFeature(document, child, fileName)
  )
}

function emitSolidChildren(document: ProjectDocument, node: FeatureNode, fileName: string): string {
  return emitListedChildren(document, node, fileName, (child) =>
    emitFeature(document, child, fileName)
  )
}

function emitListedChildren(
  document: ProjectDocument,
  node: FeatureNode,
  fileName: string,
  emitChild: (child: FeatureNode) => string
): string {
  if (!isGroupNode(node)) return ''
  const nodes = document.files[fileName]?.nodes ?? {}
  return node.childIds
    .map((id) => nodes[id])
    .filter((child): child is FeatureNode => child !== undefined && child.visible)
    .map((child) => emitChild(child))
    .filter((part) => part.length > 0)
    .join('\n')
}

function emitBoolean(document: ProjectDocument, node: BooleanNode, fileName: string): string {
  const nodes = document.files[fileName]?.nodes ?? {}
  const parts = node.childIds
    .map((id) => nodes[id])
    .filter((child): child is FeatureNode => child !== undefined && child.visible)
    .map((child) => emitFeature(document, child, fileName))
    .filter((part) => part.length > 0)
  if (parts.length === 0) return ''
  const body = `${node.kind}() {\n${indent(parts.join('\n'), 4)}\n}`
  if (node.rounding <= 0) return body
  const bounds = localBounds(document, node, fileName)
  const size = bounds ? roundingCubeSize(bounds, node.rounding) : 1000
  return `round3d(r=${formatNumber(node.rounding)}, size=${formatNumber(size)}) {\n${indent(body, 4)}\n}`
}

function emitScale(inner: string, scale: Vec3 | null): string {
  if (!scale || isNearlyOne(scale)) return inner
  return `scale(${emitVec(scale)})\n${indent(inner, 4)}`
}

function emitTranslate(inner: string, position: Vec3): string {
  return `translate(${emitVec(position)})\n${indent(inner, 4)}`
}

function emitRotate(inner: string, rotation: Vec3): string {
  if (rotation.x === 0 && rotation.y === 0 && rotation.z === 0) return inner
  return `rotate(${emitVec(rotation)})\n${indent(inner, 4)}`
}

function emitColor(inner: string, appearance: Appearance, skipDefault: boolean): string {
  const custom = appearance.color.toLowerCase() !== DEFAULT_COLOR
  const translucent = appearance.opacity < 0.999
  if (skipDefault && !custom && !translucent) return inner
  const alpha = translucent ? `, ${formatNumber(appearance.opacity)}` : ''
  return `color("${appearance.color.toLowerCase()}"${alpha})\n${indent(inner, 4)}`
}

function emitVec(value: Vec3): string {
  return `[${formatNumber(value.x)}, ${formatNumber(value.y)}, ${formatNumber(value.z)}]`
}

function emitVec2(value: Vec2): string {
  return `[${formatNumber(value.x)}, ${formatNumber(value.y)}]`
}

function emitString(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

function indent(text: string, spaces: number): string {
  const pad = ' '.repeat(spaces)
  return text
    .split('\n')
    .map((line) => (line.length > 0 ? `${pad}${line}` : line))
    .join('\n')
}
