import { describe, expect, it } from 'vitest'
import { generateOpenscad } from './openscad'
import {
  createBoolean,
  createEmptyDocument,
  createPrimitive,
  createProfile,
  createSvgProfile
} from '../document/tree'
import {
  type CuboidNode,
  type CylinderNode,
  type FeatureNode,
  type ProjectDocument,
  DEFAULT_COLOR,
  identityTransform
} from '../document/types'

describe('generateOpenscad', () => {
  it('emits a BOSL2 header for an empty model', () => {
    expect(generateOpenscad(createEmptyDocument()))
      .toBe(`// Generated by 3dev-editor. Requires BOSL2 (https://github.com/BelfrySCAD/BOSL2).
include <BOSL2/std.scad>

$fn = 48;

// Empty model
`)
  })

  it('emits a centered difference with cuboid and cyl', () => {
    const box = cuboid('box', {
      consumedBy: 'diff',
      size: { x: 30, y: 20, z: 10 }
    })
    const hole = cylinder('hole', {
      consumedBy: 'diff',
      transform: { position: { x: 10, y: 0, z: 0 }, rotation: { x: 0, y: 0, z: 0 } },
      height: 20,
      diameter: 8
    })
    const source = generateOpenscad(
      document({
        diff: {
          id: 'diff',
          name: 'Difference',
          kind: 'difference',
          visible: true,
          locked: false,
          consumedBy: null,
          childIds: ['box', 'hole'],
          rounding: 0,
          transform: identityTransform(),
          appearance: { color: DEFAULT_COLOR, opacity: 1 }
        },
        box,
        hole
      })
    )

    expect(source)
      .toBe(`// Generated by 3dev-editor. Requires BOSL2 (https://github.com/BelfrySCAD/BOSL2).
include <BOSL2/std.scad>

$fn = 48;

translate([0, 0, 0])
    difference() {
        translate([0, 0, 0])
            cuboid([30, 20, 10], anchor=CENTER);
        translate([10, 0, 0])
            cyl(h=20, d=8, anchor=CENTER);
    }
`)
  })

  it('emits color, rotation, rounding and chamfer only when they change the solid', () => {
    const colored = cuboid('colored', {
      appearance: { color: '#FF8800', opacity: 1 },
      transform: { position: { x: 0, y: 0, z: 0 }, rotation: { x: 0, y: 90, z: 0 } },
      rounding: 1
    })
    const chamfered = cuboid('chamfered', {
      transform: { position: { x: 24, y: 0, z: 0 }, rotation: { x: 0, y: 0, z: 0 } },
      chamfer: 0.5
    })
    const source = generateOpenscad(document({ colored, chamfered }))
    expect(source).toContain('color("#ff8800")')
    expect(source).toContain('rotate([0, 90, 0])')
    expect(source).toContain('cuboid([20, 20, 20], rounding=1, anchor=CENTER);')
    expect(source).toContain('cuboid([20, 20, 20], chamfer=0.5, anchor=CENTER);')
    expect(source).not.toContain('rounding=0,')
    expect(source).not.toContain('chamfer=0,')
  })

  it('omits hidden roots and hidden boolean children', () => {
    const hidden = cuboid('hidden', { visible: false })
    const kept = cuboid('kept', { consumedBy: 'diff' })
    const skipped = cylinder('skipped', { consumedBy: 'diff', visible: false })
    const source = generateOpenscad(
      document({
        hidden,
        diff: {
          id: 'diff',
          name: 'Difference',
          kind: 'difference',
          visible: true,
          locked: false,
          consumedBy: null,
          childIds: ['kept', 'skipped'],
          rounding: 0,
          transform: identityTransform(),
          appearance: { color: DEFAULT_COLOR, opacity: 1 }
        },
        kept,
        skipped
      })
    )
    expect(source).not.toContain('cyl(')
    expect(source).toContain('cuboid([20, 20, 20], anchor=CENTER);')
  })

  it('emits a sphere with opacity', () => {
    const created = createPrimitive(createEmptyDocument(), 'sphere')
    const node = created.document.nodes[created.id]
    if (node.kind !== 'sphere') throw new Error('expected sphere')
    const source = generateOpenscad({
      ...created.document,
      nodes: {
        [created.id]: {
          ...node,
          appearance: { color: DEFAULT_COLOR, opacity: 0.4 }
        }
      }
    })
    expect(source).toContain(`color("${DEFAULT_COLOR}", 0.4)`)
    expect(source).toContain('spheroid(d=16, anchor=CENTER);')
  })

  it('rounds the boolean result with round3d', () => {
    const box = cuboid('box', { consumedBy: 'union' })
    const other = cuboid('other', {
      consumedBy: 'union',
      transform: { position: { x: 20, y: 0, z: 0 }, rotation: { x: 0, y: 0, z: 0 } }
    })
    const source = generateOpenscad(
      document({
        union: {
          id: 'union',
          name: 'Union',
          kind: 'union',
          visible: true,
          locked: false,
          consumedBy: null,
          childIds: ['box', 'other'],
          rounding: 2,
          transform: identityTransform(),
          appearance: { color: DEFAULT_COLOR, opacity: 1 }
        },
        box,
        other
      })
    )
    expect(source).toContain('round3d(r=2, size=68)')
    expect(source).toContain('union()')
    expect(source).not.toContain('rounding=')
  })

  it('extrudes a centered rectangle profile', () => {
    const created = createProfile(createEmptyDocument(), 'rect')
    const source = generateOpenscad(created.document)
    expect(source).toContain('linear_extrude(height=4, center=true, twist=0, scale=1)')
    expect(source).toContain('rect(size=[20, 12], anchor=CENTER);')
    expect(source).not.toContain('rounding=')
  })

  it('imports an svg from the project assets folder', () => {
    const created = createSvgProfile(
      createEmptyDocument(),
      'logo.svg',
      '<svg viewBox="0 0 20 10" xmlns="http://www.w3.org/2000/svg"></svg>'
    )
    const source = generateOpenscad(created.document)
    const assetId = Object.keys(created.document.assets)[0]
    expect(source).toContain(`import("3dev-assets/${assetId}.svg", scale=3.78);`)
    expect(source).toContain('translate([-10, -5, 0])')
  })

  it('keeps boolean children in local coordinates after creation', () => {
    let documentState = createEmptyDocument()
    const first = createPrimitive(documentState, 'cuboid')
    documentState = first.document
    const second = createPrimitive(documentState, 'cylinder')
    documentState = patchPosition(second.document, second.id, 30)
    const result = createBoolean(documentState, 'union', [first.id, second.id])
    const source = generateOpenscad(result.document)
    expect(source).toContain('union()')
    expect(source).toContain('translate([-15, 0, 0])')
    expect(source).toContain('translate([15, 0, 0])')
  })
})

function document(nodes: Record<string, FeatureNode>): ProjectDocument {
  return { version: 1, name: 'example', units: 'mm', fn: 48, nodes, assets: {} }
}

function cuboid(id: string, patch: Partial<CuboidNode> = {}): CuboidNode {
  return {
    id,
    name: id,
    kind: 'cuboid',
    visible: true,
    locked: false,
    consumedBy: null,
    transform: identityTransform(),
    appearance: { color: DEFAULT_COLOR, opacity: 1 },
    size: { x: 20, y: 20, z: 20 },
    rounding: 0,
    chamfer: 0,
    ...patch
  }
}

function cylinder(id: string, patch: Partial<CylinderNode> = {}): CylinderNode {
  return {
    id,
    name: id,
    kind: 'cylinder',
    visible: true,
    locked: false,
    consumedBy: null,
    transform: identityTransform(),
    appearance: { color: DEFAULT_COLOR, opacity: 1 },
    height: 20,
    diameter: 12,
    ...patch
  }
}

function patchPosition(documentState: ProjectDocument, id: string, x: number): ProjectDocument {
  const node = documentState.nodes[id]
  return {
    ...documentState,
    nodes: {
      ...documentState.nodes,
      [id]: {
        ...node,
        transform: { ...node.transform, position: { x, y: 0, z: 0 } }
      }
    }
  }
}
